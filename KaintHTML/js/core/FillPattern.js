// Bit de la trama en (x, y) del lienzo; siempre true para el color sólido.
export function patternBit(index, x, y) {
    if (index <= 0 || index >= FillPatterns.length)
        return true;
    return ((FillPatterns[index][1][y & 7] >> (7 - (x & 7))) & 1) === 1;
}

// Lienzo de 8 × 8 con la trama (fg donde hay bit, bg donde no), para createPattern.
const tiles = new Map();
export function patternTile(index, fg, bg) {
    const key = `${index}/${fg.r},${fg.g},${fg.b},${fg.a ?? 255}/${bg.r},${bg.g},${bg.b},${bg.a ?? 255}`;
    let tile = tiles.get(key);
    if (!tile) {
        tile = createCanvas(8, 8);
        const ctx = context(tile), img = ctx.createImageData(8, 8);
        for (let y = 0; y < 8; ++y)
            for (let x = 0; x < 8; ++x) {
                const c = patternBit(index, x, y) ? fg : bg, i = (y * 8 + x) * 4;
                img.data[i] = c.r; img.data[i + 1] = c.g; img.data[i + 2] = c.b; img.data[i + 3] = c.a ?? 255;
            }
        ctx.putImageData(img, 0, 0);
        if (tiles.size > 64)
            tiles.clear();
        tiles.set(key, tile);
    }
    return tile;
}
