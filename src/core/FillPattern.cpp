namespace FillPattern {

int count()
{
    return int(patterns().size());
}

QString name(int index)
{
    return patterns().value(index, patterns().first()).name;
}

bool bit(int index, int x, int y)
{
    if (index <= 0 || index >= patterns().size())
        return true;
    const auto& rows = patterns()[index].rows;
    return (rows[size_t(y & 7)] >> (7 - (x & 7))) & 1;
}

} // namespace FillPattern
